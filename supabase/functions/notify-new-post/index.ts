import { serve } from "https://deno.land/std@0.168.0/http/server.ts";
import { createClient } from 'https://esm.sh/@supabase/supabase-js@2';

serve(async (req) => {
  try {
    const supabaseUrl = Deno.env.get('SUPABASE_URL')!;
    const supabaseKey = Deno.env.get('SUPABASE_SERVICE_ROLE_KEY')!;
    const supabase = createClient(supabaseUrl, supabaseKey);

    // Récupère la nouvelle publication depuis le webhook de base de données
    const payload = await req.json();
    const newPost = payload.record;

    // Sélectionne tous les tokens enregistrés dans la table
    const { data: tokensData } = await supabase.from('push_tokens').select('token');
    if (!tokensData || tokensData.length === 0) return new Response("Aucun token trouvé", { status: 200 });

    const expoPushTokens = tokensData.map(t => t.token);

    // Crée le message de la notification
    const message = {
      to: expoPushTokens,
      sound: 'default',
      title: 'Nouveau contenu sur Ganbanaaxu !',
      body: newPost.caption ? newPost.caption.substring(0, 50) + '...' : 'Une nouvelle publication vient d\'être ajoutée.',
    };

    // Envoie le message via l'API d'Expo
    await fetch('https://exp.host/--/api/v2/push/send', {
      method: 'POST',
      headers: {
        Accept: 'application/json',
        'Accept-encoding': 'gzip, deflate',
        'Content-Type': 'application/json',
      },
      body: JSON.stringify(message),
    });

    return new Response(JSON.stringify({ success: true }), { headers: { "Content-Type": "application/json" } });
  } catch (error) {
    return new Response(JSON.stringify({ error: error.message }), { status: 500 });
  }
});